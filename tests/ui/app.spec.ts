import { test, expect } from '@playwright/test';
test('offline routine, counter persistence, RTL and mobile layout', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('heading', { name: /Assalamu/ })).toBeVisible();
  await page.getByRole('button', { name: 'Routines', exact: true }).first().click();
  await page.getByRole('button', { name: 'Tasbih', exact: true }).click();
  await page.getByRole('button', { name: 'Add routine', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Routine name').fill('Evening dhikr');
  await dialog.getByLabel('Target', { exact: true }).fill('5');
  await dialog.getByLabel('Dhikr text').fill('Astaghfirullah');
  await dialog.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Evening dhikr' })).toBeVisible();
  const counter = page.getByRole('button', { name: 'Tap to count', exact: true });
  await counter.click();
  await counter.click();
  await expect(counter.locator('strong')).toHaveText('2');
  await page.reload();
  await page.getByRole('button', { name: 'Routines', exact: true }).first().click();
  await page.getByRole('button', { name: 'Tasbih', exact: true }).click();
  await expect(counter.locator('strong')).toHaveText('2');
  await counter.click();
  await counter.click();
  await counter.click();
  await expect(counter.locator('strong')).toHaveText('5');
  await expect(counter).toBeDisabled();
  const snapshot = await page.evaluate(() => JSON.parse(localStorage.getItem('salahguard')!));
  expect(snapshot.records.filter((r: any) => r.entity === 'routine_completions')).toHaveLength(1);
  expect(snapshot.queue.length).toBeGreaterThan(0);
  await page.getByRole('button', { name: 'More', exact: true }).click();
  await page.getByRole('button', { name: 'Settings', exact: false }).click();
  await page.getByRole('button', { name: 'Language / Appearance', exact: true }).click();
  await page.getByLabel('Language', { exact: true }).selectOption('ur');
  await expect(page.locator('html')).toHaveAttribute('dir', 'rtl');
  await expect(page.getByRole('heading', { name: 'ترتیبات', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: '.tools/settings-urdu-mobile.png', fullPage: true });
  expect(errors).toEqual([]);
});
test('routine form remains stable while the dashboard clock ticks', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Routines', exact: true }).first().click();
  await page.getByRole('button', { name: 'Add routine', exact: true }).click();
  const field = page.getByRole('dialog').getByLabel('Routine name');
  await field.pressSequentially('A careful daily reading', { delay: 120 });
  await expect(field).toHaveValue('A careful daily reading');
  await expect(field).toBeFocused();
});
