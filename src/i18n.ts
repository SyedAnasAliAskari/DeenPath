export function translator(lang: Lang) {
  return (key: Key | ExtraKey) =>
    key in extra
      ? extraText(key as ExtraKey, lang)
      : { en, ur, ar }[lang][key as Key] || en[key as Key];
}
export function localizationCoverage() {
  return {
    ur: Object.keys(en).filter((k) => !(ur as any)[k]),
    ar: Object.keys(en).filter((k) => !(ar as any)[k]),
  };
}
export const prayerLabel = (name: string, lang: Lang, day?: string) => {
  if (name === 'Dhuhr' && day && new Date(day + 'T12:00Z').getUTCDay() === 5) name = 'Jummah';
  return lang === 'en'
    ? name
    : {
        Fajr: 'فجر',
        Dhuhr: lang === 'ur' ? 'ظہر' : 'ظهر',
        Jummah: lang === 'ur' ? 'جمعہ' : 'الجمعة',
        Asr: 'عصر',
        Maghrib: 'مغرب',
        Isha: lang === 'ur' ? 'عشاء' : 'عشاء',
      }[name] || name;
};
